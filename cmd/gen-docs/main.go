// Command gen-docs generates perch's manpages and the CLI reference for the
// documentation website from the urfave/cli command tree.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/synqronlabs/perch/internal/cli"
	urfave "github.com/urfave/cli/v3"
)

const generatedMarker = "Code generated by cmd/gen-docs; DO NOT EDIT."

var environment = []string{
	"PERCH_CONFIG           path to perch.yaml",
	"PERCH_DATA_DIR         override data_dir",
	"PERCH_HOSTNAME         override hostname",
	"PERCH_IMAP_USER        default account username for perch mail",
	"PERCH_IMAP_PASSWORD    account password for perch mail",
	"PERCH_S3_SECRET_KEY    S3 secret when storage.s3.secret_key_env selects it",
	"PERCH_MXRAVEN_KEY_SECRET              mxRaven MTA listener secret",
	"PERCH_MXRAVEN_SUBMISSION_KEY_SECRET   mxRaven submission listener secret",
	"MXRAVEN_API_TOKEN      legacy control-plane token used by perch setup",
	"MXRAVEN_ISSUER         mxRaven identity issuer URL",
	"MXRAVEN_DASHBOARD_URL  mxRaven dashboard URL used for connected-app approval",
	"MXRAVEN_CLIENT_ID      registered perch connected-app client ID",
}

type docNode struct {
	Command  *urfave.Command
	Path     []string
	Parent   *docNode
	Children []*docNode
	Weight   int
}

func (n *docNode) Name() string {
	return strings.Join(n.Path, " ")
}

func (n *docNode) PageName() string {
	return strings.Join(n.Path, "-")
}

func (n *docNode) Paragraphs() []string {
	if doc, ok := commandDocs[n.Name()]; ok && len(doc.Paragraphs) > 0 {
		return doc.Paragraphs
	}
	if usage := strings.TrimSpace(n.Command.Usage); usage != "" {
		return []string{usage}
	}
	return nil
}

func (n *docNode) Description() string {
	return strings.Join(n.Paragraphs(), "\n\n")
}

func (n *docNode) ShortDescription() string {
	if doc, ok := commandDocs[n.Name()]; ok && strings.TrimSpace(doc.Summary) != "" {
		return doc.Summary
	}
	if value := strings.TrimSpace(n.Command.Usage); value != "" {
		return value
	}
	return n.Description()
}

func (n *docNode) Examples() []string {
	if doc, ok := commandDocs[n.Name()]; ok && len(doc.Examples) > 0 {
		return doc.Examples
	}
	_, examples := splitUsageText(usageText(n))
	if examples == "" {
		return nil
	}
	return []string{examples}
}

func (n *docNode) Notes() []string {
	if doc, ok := commandDocs[n.Name()]; ok && len(doc.Notes) > 0 {
		return doc.Notes
	}
	intro, _ := splitUsageText(usageText(n))
	if intro != "" && intro != n.Description() {
		return []string{intro}
	}
	return nil
}

func (n *docNode) Environment() []string {
	if doc, ok := commandDocs[n.Name()]; ok {
		return doc.Environment
	}
	return nil
}

func (n *docNode) Synopsis() string {
	parts := []string{n.Name(), "[OPTIONS]"}
	if len(n.Children) > 0 {
		parts = append(parts, "COMMAND")
	}
	if strings.TrimSpace(n.Command.ArgsUsage) != "" {
		parts = append(parts, strings.TrimSpace(n.Command.ArgsUsage))
	}
	return strings.Join(parts, " ")
}

func (n *docNode) Flags() []flagInfo {
	var flags []flagInfo
	seen := make(map[string]struct{})
	lineage := n.Lineage()
	for _, ancestor := range lineage {
		for _, flag := range ancestor.Command.Flags {
			names := flag.Names()
			if len(names) == 0 {
				continue
			}
			if _, ok := seen[names[0]]; ok {
				continue
			}
			if visible, ok := flag.(urfave.VisibleFlag); ok && !visible.IsVisible() {
				continue
			}
			seen[names[0]] = struct{}{}
			doc, ok := flag.(urfave.DocGenerationFlag)
			if !ok {
				flags = append(flags, flagInfo{Display: flagDisplay(flag, false, false), Usage: flag.String()})
				continue
			}
			multi := false
			if multiFlag, ok := flag.(urfave.DocGenerationMultiValueFlag); ok {
				multi = multiFlag.IsMultiValueFlag()
			}
			usage := doc.GetUsage()
			if names[0] == "config" {
				usage += " (default: ~/.config/perch/perch.yaml)"
			} else if value := defaultText(doc); value != "" && doc.IsDefaultVisible() {
				usage += " (default: " + value + ")"
			}
			flags = append(flags, flagInfo{
				Display: flagDisplay(flag, doc.TakesValue(), multi),
				Usage:   usage,
			})
		}
	}
	flags = append(flags, flagInfo{Display: "--help, -h", Usage: "show help"})
	if len(n.Path) == 1 {
		flags = append(flags, flagInfo{Display: "--version, -v", Usage: "print the version"})
	}
	return flags
}

func (n *docNode) Lineage() []*docNode {
	var lineage []*docNode
	for current := n; current != nil; current = current.Parent {
		lineage = append(lineage, current)
	}
	for i, j := 0, len(lineage)-1; i < j; i, j = i+1, j-1 {
		lineage[i], lineage[j] = lineage[j], lineage[i]
	}
	return lineage
}

func (n *docNode) SeeAlso() []string {
	names := []string{"perch"}
	for i := 1; i <= len(n.Path); i++ {
		names = append(names, strings.Join(n.Path[:i], "-"))
	}
	for _, child := range n.Children {
		names = append(names, child.PageName())
	}
	sort.Strings(names)
	unique := names[:0]
	for _, name := range names {
		if len(unique) == 0 || unique[len(unique)-1] != name {
			unique = append(unique, name)
		}
	}
	out := unique[:0]
	for _, name := range unique {
		if name != n.PageName() {
			out = append(out, name)
		}
	}
	return out
}

type flagInfo struct {
	Display string
	Usage   string
}

func main() {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		fatal("cannot locate generator")
	}
	rootDir := filepath.Dir(filepath.Dir(filepath.Dir(file)))
	if err := run(rootDir); err != nil {
		fatal(err.Error())
	}
}

func fatal(message string) {
	fmt.Fprintln(os.Stderr, "gen-docs:", message)
	os.Exit(1)
}

func run(rootDir string) error {
	manDir := filepath.Join(rootDir, "man")
	cliDir := filepath.Join(rootDir, "website", "content", "docs", "cli")
	if err := os.MkdirAll(manDir, 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(cliDir, 0o755); err != nil {
		return err
	}
	if err := cleanGenerated(manDir, ".1"); err != nil {
		return err
	}
	if err := cleanGenerated(cliDir, ".md"); err != nil {
		return err
	}

	root := buildTree(cli.RootCommand())
	for _, node := range rootTree(root) {
		if err := writeManpage(filepath.Join(manDir, node.PageName()+".1"), node); err != nil {
			return err
		}
		if err := writeMarkdown(filepath.Join(cliDir, node.PageName()+".md"), node); err != nil {
			return err
		}
	}
	return writeCLIIndex(filepath.Join(cliDir, "_index.md"), root)
}

func buildTree(root *urfave.Command) *docNode {
	node := &docNode{Command: root, Path: []string{"perch"}}
	var build func(*docNode)
	build = func(current *docNode) {
		for _, child := range current.Command.Commands {
			path := append(append([]string(nil), current.Path...), child.Name)
			childNode := &docNode{Command: child, Path: path, Parent: current}
			current.Children = append(current.Children, childNode)
			build(childNode)
		}
	}
	build(node)
	return node
}

func rootTree(root *docNode) []*docNode {
	var nodes []*docNode
	var walk func(*docNode)
	walk = func(node *docNode) {
		node.Weight = len(nodes) * 10
		nodes = append(nodes, node)
		for _, child := range node.Children {
			walk(child)
		}
	}
	walk(root)
	return nodes
}

func cleanGenerated(dir, suffix string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), suffix) {
			continue
		}
		if err := os.Remove(filepath.Join(dir, entry.Name())); err != nil {
			return err
		}
	}
	return nil
}

func flagDisplay(flag urfave.Flag, takesValue, multi bool) string {
	names := flag.Names()
	parts := make([]string, 0, len(names))
	for i, name := range names {
		if i == 0 {
			parts = append(parts, "--"+name)
		} else if len(name) == 1 {
			parts = append(parts, "-"+name)
		} else {
			parts = append(parts, "--"+name)
		}
	}
	display := strings.Join(parts, ", ")
	if takesValue {
		display += " <value>"
		if multi {
			display += "..."
		}
	}
	return display
}

func defaultText(doc urfave.DocGenerationFlag) string {
	if value := doc.GetDefaultText(); value != "" {
		return value
	}
	if !doc.TakesValue() {
		return ""
	}
	value := doc.GetValue()
	if value == "" || value == "false" {
		return ""
	}
	return value
}

func writeManpage(path string, node *docNode) error {
	var out bytes.Buffer
	title := strings.ToUpper(node.PageName())
	out.WriteString(".TH \"" + title + "\" \"1\" \"" + manDate() + "\" \"perch\" \"perch manual\"\n")
	out.WriteString(".SH NAME\n")
	out.WriteString(roffText(node.PageName()) + " \\- " + roffText(lowerFirst(node.ShortDescription())) + "\n")
	out.WriteString(".SH SYNOPSIS\n")
	out.WriteString(".B " + roffText(node.Synopsis()) + "\n")
	out.WriteString(".SH DESCRIPTION\n")
	writeRoffParagraphs(&out, node.Paragraphs())

	if aliases := node.Command.Aliases; len(aliases) > 0 {
		out.WriteString(".PP\nAliases: " + roffText(strings.Join(aliases, ", ")) + ".\n")
	}

	if notes := node.Notes(); len(notes) > 0 {
		out.WriteString(".SH NOTES\n")
		for _, note := range notes {
			out.WriteString(".IP \\(bu 2\n" + roffProse(note) + "\n")
		}
	}

	out.WriteString(".SH OPTIONS\n")
	for _, flag := range node.Flags() {
		out.WriteString(".TP\n")
		out.WriteString(".B " + roffText(flag.Display) + "\n")
		out.WriteString(roffText(flag.Usage) + "\n")
	}

	if len(node.Children) > 0 {
		out.WriteString(".SH COMMANDS\n")
		for _, child := range node.Children {
			out.WriteString(".TP\n")
			out.WriteString(".B " + roffText(child.Command.Name) + "\n")
			usage := child.Command.Usage
			if len(child.Command.Aliases) > 0 {
				usage += " (aliases: " + strings.Join(child.Command.Aliases, ", ") + ")"
			}
			out.WriteString(roffText(usage) + "\n")
		}
	}

	if examples := node.Examples(); len(examples) > 0 {
		out.WriteString(".SH EXAMPLES\n")
		out.WriteString(".nf\n" + roffText(strings.Join(examples, "\n\n")) + "\n.fi\n")
	}

	env := node.Environment()
	if len(node.Path) == 1 {
		env = environment
	}
	if len(env) > 0 {
		out.WriteString(".SH ENVIRONMENT\n")
		writeRoffEnvironment(&out, env)
	}

	if len(node.Path) == 1 {
		out.WriteString(".SH FILES\n")
		out.WriteString(".TP\n.B ~/.config/perch/perch.yaml\nDefault configuration file ($XDG_CONFIG_HOME/perch/perch.yaml).\n")
		out.WriteString(".TP\n.B ~/.config/perch/perch.db\nDefault SQLite database when data_dir is not overridden.\n")
		out.WriteString(".SH EXIT STATUS\n")
		out.WriteString(".TP\n.B 0\nSuccess.\n")
		out.WriteString(".TP\n.B 1\nRuntime or usage error.\n")
		out.WriteString(".TP\n.B 2\nCommand-line usage error.\n")
	}

	out.WriteString(".SH SEE ALSO\n")
	out.WriteString(".PP\n")
	refs := node.SeeAlso()
	for i, ref := range refs {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString(`\fB` + roffText(ref) + `\fR(1)`)
	}
	out.WriteString("\n")
	return os.WriteFile(path, out.Bytes(), 0o644)
}

func writeRoffParagraphs(out *bytes.Buffer, paragraphs []string) {
	for _, paragraph := range paragraphs {
		out.WriteString(".PP\n" + roffProse(paragraph) + "\n")
	}
}

func writeRoffEnvironment(out *bytes.Buffer, entries []string) {
	for _, entry := range entries {
		fields := strings.Fields(entry)
		if len(fields) == 0 {
			continue
		}
		out.WriteString(".TP\n")
		out.WriteString(".B " + roffText(fields[0]) + "\n")
		rest := strings.TrimSpace(strings.TrimPrefix(entry, fields[0]))
		out.WriteString(roffText(rest) + "\n")
	}
}

func writeMarkdown(path string, node *docNode) error {
	var out bytes.Buffer
	out.WriteString("---\n")
	out.WriteString("title: " + strconv.Quote(node.Name()) + "\n")
	out.WriteString("weight: " + strconv.Itoa(node.Weight) + "\n")
	out.WriteString("bookToc: true\n")
	out.WriteString("---\n\n")
	out.WriteString("<!-- " + generatedMarker + " -->\n\n")
	out.WriteString("## Synopsis\n\n```text\n" + node.Synopsis() + "\n```\n\n")
	out.WriteString("## Description\n\n" + node.Description() + "\n")

	if aliases := node.Command.Aliases; len(aliases) > 0 {
		out.WriteString("\nAliases: `" + strings.Join(aliases, "`, `") + "`.\n")
	}

	if notes := node.Notes(); len(notes) > 0 {
		out.WriteString("\n## Notes\n\n")
		for _, note := range notes {
			out.WriteString("- " + note + "\n")
		}
	}

	out.WriteString("\n## Options\n\n")
	out.WriteString("| Option | Description |\n| --- | --- |\n")
	for _, flag := range node.Flags() {
		out.WriteString("| `" + escapeTable(flag.Display) + "` | " + escapeTable(flag.Usage) + " |\n")
	}

	if len(node.Children) > 0 {
		out.WriteString("\n## Commands\n\n")
		out.WriteString("| Command | Description |\n| --- | --- |\n")
		for _, child := range node.Children {
			link := fmt.Sprintf("[%s](%s.md)", child.Name(), child.PageName())
			out.WriteString("| " + link + " | " + escapeTable(child.Command.Usage) + " |\n")
		}
	}

	if examples := node.Examples(); len(examples) > 0 {
		out.WriteString("\n## Examples\n\n```sh\n" + strings.Join(examples, "\n\n") + "\n```\n")
	}

	env := node.Environment()
	if len(env) > 0 {
		out.WriteString("\n## Environment\n\n")
		out.WriteString("| Variable | Purpose |\n| --- | --- |\n")
		for _, entry := range env {
			fields := strings.Fields(entry)
			if len(fields) == 0 {
				continue
			}
			rest := strings.TrimSpace(strings.TrimPrefix(entry, fields[0]))
			out.WriteString("| `" + fields[0] + "` | " + escapeTable(rest) + " |\n")
		}
	}

	out.WriteString("\n## See also\n\n")
	for _, ref := range node.SeeAlso() {
		if ref == node.PageName() {
			continue
		}
		out.WriteString("- [" + strings.ReplaceAll(ref, "-", " ") + "](" + ref + ".md)\n")
	}
	return os.WriteFile(path, out.Bytes(), 0o644)
}

func writeCLIIndex(path string, root *docNode) error {
	var out bytes.Buffer
	out.WriteString("---\n")
	out.WriteString("title: \"CLI reference\"\n")
	out.WriteString("weight: 90\n")
	out.WriteString("bookToc: false\n")
	out.WriteString("bookCollapseSection: true\n")
	out.WriteString("---\n\n")
	out.WriteString("<!-- " + generatedMarker + " -->\n\n")
	out.WriteString("Command reference generated from the `perch` command tree. Every command also accepts `--help` for its installed version.\n\n")
	out.WriteString("| Command | Description |\n| --- | --- |\n")
	for _, child := range root.Children {
		link := fmt.Sprintf("[%s](%s.md)", child.Name(), child.PageName())
		out.WriteString("| " + link + " | " + escapeTable(child.Command.Usage) + " |\n")
	}
	return os.WriteFile(path, out.Bytes(), 0o644)
}

func splitUsageText(value string) (string, string) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", ""
	}
	for _, marker := range []string{"\nExamples:", "Examples:"} {
		if index := strings.Index(value, marker); index >= 0 {
			return strings.TrimSpace(value[:index]), strings.TrimSpace(value[index+len(marker):])
		}
	}
	return value, ""
}

func usageText(node *docNode) string {
	value := strings.TrimSpace(node.Command.UsageText)
	if len(node.Children) == 0 && strings.HasPrefix(value, node.Name()) {
		if index := strings.IndexByte(value, '\n'); index >= 0 {
			return strings.TrimSpace(value[index+1:])
		}
		return ""
	}
	return value
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}

func manDate() string {
	if value := os.Getenv("SOURCE_DATE_EPOCH"); value != "" {
		seconds, err := strconv.ParseInt(value, 10, 64)
		if err == nil {
			return time.Unix(seconds, 0).UTC().Format("2006-01-02")
		}
	}
	return ""
}

func roffText(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, "-", `\-`)
	lines := strings.Split(value, "\n")
	for i, line := range lines {
		if strings.HasPrefix(line, ".") || strings.HasPrefix(line, "'") {
			lines[i] = `\&` + line
		}
	}
	return strings.Join(lines, "\n")
}

func roffProse(value string) string {
	return roffText(strings.ReplaceAll(value, "`", ""))
}

func escapeTable(value string) string {
	return strings.ReplaceAll(value, "|", `\|`)
}
